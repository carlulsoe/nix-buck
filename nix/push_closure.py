"""Upload relocated closures to a REAPI CAS, pin them for buck2, and index
their store paths for the substituter.

Each closure goes up as one tree, pinned in OUT.bzl by its root Directory
digest. Each store path in it is a subtree with a digest of its own, indexed
with its references so the substituter can serve it to Nix. A store path in
several closures must have the same digest in each, and the same as any
earlier upload: one name, one content.

usage: push_closure.py OUT.bzl INDEX CLOSURES_JSON
  CLOSURES_JSON: name -> {"tree": a relocated closure (nix/store and
  closure.json, by nix/relocate.py), "originals": role -> nixpkgs basename}.
"""

import json
import os
import sys

import cas
from storepath import STORE, add_to_index


def push(index, closure, originals):
    digest, _ = cas.upload_dir(closure)
    store = cas.subdirs(cas.subdirs(cas.subdirs(digest)["nix"])["store"])
    with open(os.path.join(closure, "closure.json")) as f:
        meta = json.load(f)
    if sorted(store) != sorted(meta["references"]):
        raise SystemExit(f"{closure}: uploaded tree does not match closure.json")
    for base, references in meta["references"].items():
        add_to_index(index, STORE + base, store[base], references)
    return {
        "digest": digest,
        "roots": meta["roots"],
        "originals": originals,
        "references": meta["references"],
    }


def main(out, index, closures_file):
    with open(closures_file) as f:
        closures = json.load(f)
    pinned = {}
    for name, closure in sorted(closures.items()):
        pinned[name] = push(index, closure["tree"], closure["originals"])
        print(f"{name}: {pinned[name]['digest']} ({len(pinned[name]['references'])} store paths)")
    with open(out, "w") as f:
        f.write("# Generated by `nix run .#push-closure`: the relocated closures, each\n"
                "# pinned by its REAPI Directory digest. Do not edit.\n"
                "NIX_CLOSURES = " + json.dumps(pinned, indent=4, sort_keys=True) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:])
