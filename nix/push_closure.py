"""Upload a relocated closure to a REAPI CAS and pin it for buck2.

The closure goes up as one tree and is pinned by its root Directory digest
in gcc_closure.bzl. The tree is checked to hold exactly the store paths
closure.json lists.

usage: push_closure.py CLOSURE OUT.bzl   (CLOSURE contains nix/store and closure.json)
"""

import json
import os
import subprocess
import sys
import tempfile

CAS = os.environ.get("CAS", "127.0.0.1:50051")
FLAGS = [f"--service={CAS}", "--service_no_security", "--instance=main", "--alsologtostderr=false"]


def varint(b, i):
    r = s = 0
    while True:
        c = b[i]
        i += 1
        r |= (c & 0x7F) << s
        s += 7
        if c < 0x80:
            return r, i


def fields(b):
    """Top-level (field, value) pairs of a protobuf message; enough for Directory."""
    i = 0
    while i < len(b):
        key, i = varint(b, i)
        field, wire = key >> 3, key & 7
        if wire == 2:
            n, i = varint(b, i)
            yield field, b[i:i + n]
            i += n
        elif wire == 0:
            v, i = varint(b, i)
            yield field, v
        else:
            raise ValueError(f"unexpected wire type {wire}")


def digest_of(msg):
    d = dict(fields(msg))
    return "{}:{}".format(d[1].decode(), d.get(2, 0))


def subdirs(digest):
    """name -> digest of the DirectoryNodes (field 2) of a Directory blob."""
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "blob")
        subprocess.run(["remotetool", "--operation=download_blob", *FLAGS,
                        "--digest=" + digest.replace(":", "/"), "--path=" + path], check=True)
        with open(path, "rb") as f:
            blob = f.read()
    out = {}
    for field, node in fields(blob):
        if field == 2:
            n = dict(fields(node))
            out[n[1].decode()] = digest_of(n[2])
    return out


def main(closure, out):
    with tempfile.TemporaryDirectory() as tmp:
        stats = os.path.join(tmp, "upload.json")
        subprocess.run(["remotetool", "--operation=upload_dir", *FLAGS, "--symlink_behavior=preserve",
                        "--path=" + closure, "--json=" + stats], check=True)
        with open(stats) as f:
            root = json.load(f)["RootDigest"]
    digest = "{}:{}".format(root["Hash"], root["Size"])
    store = subdirs(subdirs(subdirs(digest)["nix"])["store"])

    with open(os.path.join(closure, "closure.json")) as f:
        meta = json.load(f)
    if sorted(store) != sorted(meta["paths"]):
        raise SystemExit("uploaded tree does not match closure.json")
    pinned = {"digest": digest, "roots": meta["roots"], "closure": meta["paths"]}
    with open(out, "w") as f:
        f.write("# Generated by `nix run .#push-closure`: the relocated gcc closure,\n"
                "# pinned by its REAPI Directory digest. Do not edit.\n"
                "GCC_CLOSURE = " + json.dumps(pinned, indent=4) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:])
